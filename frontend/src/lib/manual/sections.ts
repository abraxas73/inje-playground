export function searchManual(query: string) {
  const terms = query.trim().toLocaleLowerCase("ko-KR").split(/\s+/).filter(Boolean);
  return manualSections.filter((s) => {
    const text = [s.title, s.category, s.description, ...s.steps, s.note ?? "", ...(s.links ?? []).map((l) => l.label), ...(s.images ?? []).map((i) => i.caption), s.app ? `${s.app} 앱` : ""].join(" ").toLocaleLowerCase("ko-KR");
    return terms.every((term) => text.includes(term));
  });
}
