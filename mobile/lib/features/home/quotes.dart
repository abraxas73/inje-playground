/// 홈 "오늘의 한 줄". 널리 알려진 격언·속담만(출처 표기). 날짜로 고르므로 같은 날은 모두 같은 글을 본다.
class Quote {
  const Quote(this.text, this.source);
  final String text, source;
  @override
  bool operator ==(Object other) => other is Quote && other.text == text && other.source == source;
  @override
  int get hashCode => Object.hash(text, source);
}

Quote dailyQuote(DateTime now) {
  final dayOfYear = now.difference(DateTime(now.year, 1, 1)).inDays;
  return quotes[(now.year * 366 + dayOfYear) % quotes.length];
}

